const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../Resources/ProfileWeb/app.js'), 'utf8');
const viewport = { scrollTop: 0, removeAttribute() {}, getBoundingClientRect: () => ({ left: 10, top: 20 }) };
let scheduled = 0;
const timers = new Map();
let timerID = 0;
const context = vm.createContext({ assert, setTimeout: callback => { timers.set(++timerID, callback); return timerID; }, clearTimeout: id => timers.delete(id), $: () => viewport, requestAnimationFrame: () => ++scheduled });
vm.runInContext('const state = { profile: {}, zoom: 1 };' +
  source.slice(source.indexOf('  const flameView'), source.indexOf('  function formatTime')), context);
vm.runInContext(`
flameView.width = 1000;
setZoom(2, .25, 250);
assert.equal(flameView.left, 250);
assert.equal((flameView.left + 250) / (flameView.width * state.zoom), .25);
setZoom(4, .25, 250);
assert.equal(flameView.left, 750);
assert.equal(flameView.frame, 1);
setZoom(100, 1, 500);
assert.equal(state.zoom, 100);
assert.equal(flameView.left, 99000);
setZoom(1000, .25, 250);
assert.equal(state.zoom, 1000);
assert.equal(flameView.left, 249750);
assert.equal((flameView.left + 250) / (flameView.width * state.zoom), .25);
setZoom(Infinity);
setZoom(NaN);
assert.equal(state.zoom, 1000);
setZoom(0, 0, 0);
assert.equal(state.zoom, 1);
assert.equal(flameView.left, 0);
beginPinch(260, 100);
updatePinch(3);
assert.equal(state.zoom, 3);
assert.equal(flameView.left, 500);
updatePinch(NaN);
assert.equal(state.zoom, 3);
endPinch();
assert.equal(state.pinch, null);
const row = [{x:0,width:.2}, {x:.3,width:.2}, {x:.5,width:.5}];
assert.equal(firstFlameItem(row, 0), 0);
assert.equal(firstFlameItem(row, .2), 1);
assert.equal(firstFlameItem(row, .5), 2);
assert.equal(firstFlameItem(row, 1), 3);
state.zoom = 1; flameView.left = 0; flameView.rows = [row];
assert.equal(flameItemAt(110, 25), row[0]);
assert.equal(flameItemAt(260, 25), null);
assert.equal(flameItemAt(510, 25), row[2]);
assert.equal(flameItemAt(1010, 25), null);
assert.equal(flameItemAt(110, 60), null);
`, context);
assert.equal(scheduled, 1);
vm.runInContext(`
flameView.boxes = { style: {} };
flameView.rows = [[{x:.25, width:.125, box:{style:{}}}]];
state.zoom = 16;
commitFlameBoxes();
assert.equal(flameView.boxes.style.width, '16000px');
assert.equal(flameView.rows[0][0].box.style.left, '4000px');
assert.equal(flameView.rows[0][0].box.style.width, '2000px');
assert.equal(flameView.boxes.style.transform, 'none');
assert.equal(flameView.boxes.style.willChange, 'auto');
assert.equal(flameView.boxZoom, 16);
setZoom(8, .5, 500);
`, context);
assert.equal(timers.size, 1);
vm.runInContext('beginPinch(510); updatePinch(.5);', context);
assert.equal(timers.size, 0);
vm.runInContext(`
endPinch();
assert.equal(flameView.commitDirty, true);
commitFlameBoxes();
assert.equal(flameView.boxZoom, 4);
assert.equal(flameView.rows[0][0].box.style.width, '500px');
assert.equal(flameView.boxes.style.transform, 'none');
`, context);
vm.runInContext(`
flameView.rows = [[{x:.25, width: .0001, box:{style:{}}}]];
setZoom(1000, .25, 0);
commitFlameBoxes();
assert.equal(flameView.rows[0][0].box.style.width, '100px');
assert.equal(flameView.boxes.style.transform, 'none');
`, context);
console.log('PASS flame zoom anchoring, coalescing, hit testing, and final-resolution box layout');
